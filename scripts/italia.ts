export const SAGOME = [PENISOLA, SICILIA, SARDEGNA]

function pointInPolygon([lng, lat]: LngLat, poly: LngLat[]): boolean {
  let inside = false
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i]
    const [xj, yj] = poly[j]
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside
    }
  }
  return inside
}

export function isInItalia(lng: number, lat: number): boolean {
  return SAGOME.some((poly) => pointInPolygon([lng, lat], poly))
}

